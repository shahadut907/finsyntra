/**
 * PDF export for FinSyntra AI chat conversations.
 *
 * The transcript is rendered with the same safe Markdown renderer as the chat
 * (MessageContent: React nodes only, no injected HTML) into a print-only
 * element of this page, and handed to the browser's print engine ("Save as
 * PDF"). That engine shapes Bangla correctly (conjuncts, vowel signs), wraps
 * long words and table cells, repeats table headers and paginates, and keeps
 * the text selectable and extractable. The former jsPDF path drew every
 * message as one Helvetica string: Bangla came out as broken glyphs, Markdown
 * stayed raw, and long lines and tall messages were clipped.
 *
 * No iframe is used: the production CSP (frame-ancestors 'none') would also
 * apply to a same-origin print frame, and this page already has the fonts.
 */

import React from 'react';
import { createRoot } from 'react-dom/client';
import { flushSync } from 'react-dom';
import { format } from 'date-fns';
import { MessageContent } from '../components/chat/MessageContent';

const BANGLA = /[ঀ-৿]/;
const ROOT_ID = 'fs-print-root';
const STYLE_ID = 'fs-print-style';

/** Uploaded files are stored as <name>_<32 hex><ext>; show <name><ext>. */
export const displaySourceName = (source) =>
  String(source?.name || source || '').replace(/_[0-9a-f]{32}(?=\.[^.]+$)/, '');

const formatTime = (value) => {
  if (!value) return '';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? '' : format(date, 'PP, p');
};

export function ChatExportDocument({
  messages = [],
  currentUserName = 'User',
  tenant = 'FinSyntra Technologies',
  department = 'General',
  exportedAt = new Date()
}) {
  const questions = messages.filter((m) => m.sender === 'user').length;
  const meta = [
    ['User', currentUserName],
    ['Organization', tenant],
    ['Department', department],
    ['Messages', `${messages.length} (${questions} questions, ${messages.length - questions} answers)`],
    ['Exported', format(exportedAt, "PP, p 'UTC'xxx")]
  ];

  return (
    <article className="fsx" lang="en">
      <header className="fsx-head">
        <p className="fsx-brand">FinSyntra <span>AI</span></p>
        <p className="fsx-tag">Conversation transcript</p>
        <dl className="fsx-meta">
          {meta.map(([label, value]) => (
            <div key={label}>
              <dt>{label}</dt>
              <dd>{value}</dd>
            </div>
          ))}
        </dl>
      </header>

      <main className="fsx-transcript">
        {messages.map((msg, index) => {
          const isUser = msg.sender === 'user';
          const text = String(msg.text ?? msg.content ?? '');
          const sources = isUser ? [] : [...new Set((msg.sources || []).map(displaySourceName))].filter(Boolean);
          return (
            <section
              key={msg.id || index}
              className={`fsx-msg ${isUser ? 'fsx-user' : 'fsx-ai'}`}
              lang={BANGLA.test(text) ? 'bn' : undefined}
            >
              <p className="fsx-msg-head">
                <span className="fsx-who">{isUser ? 'You' : 'FinSyntra AI'}</span>
                <time>{formatTime(msg.timestamp)}</time>
              </p>
              {isUser ? <p className="fsx-plain">{text}</p> : <MessageContent text={text} />}
              {sources.length > 0 && (
                <div className="fsx-sources">
                  <p>Sources</p>
                  <ul>
                    {sources.map((name) => <li key={name}>{name}</li>)}
                  </ul>
                </div>
              )}
            </section>
          );
        })}
      </main>

      <footer className="fsx-end">
        <p>
          <strong>Confidential.</strong> This document contains proprietary information from {tenant}.
          Generated by FinSyntra AI on {format(exportedAt, "PPPP 'at' p 'UTC'xxx")}.
        </p>
      </footer>
    </article>
  );
}

