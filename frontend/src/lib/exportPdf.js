/**
 * Open the print dialog for the transcript; the user chooses "Save as PDF".
 * Resolves after the dialog closes (or false when there is nothing to export).
 */
export async function exportChatToPdf({
  messages = [],
  fileName = 'finsyntra-chat-export',
  currentUserName = 'User',
  tenant = 'FinSyntra Technologies',
  department = 'General'
} = {}) {
  if (!messages || messages.length === 0) {
    console.warn('No messages to export');
    return false;
  }

  document.getElementById(ROOT_ID)?.remove();
  document.getElementById(STYLE_ID)?.remove();

  const exportedAt = new Date();
  const style = document.createElement('style');
  style.id = STYLE_ID;
  style.textContent = PRINT_CSS;
  const host = document.createElement('div');
  host.id = ROOT_ID;
  document.head.appendChild(style);
  document.body.appendChild(host);

  const root = createRoot(host);
  flushSync(() => {
    root.render(
      <ChatExportDocument
        messages={messages}
        currentUserName={currentUserName}
        tenant={tenant}
        department={department}
        exportedAt={exportedAt}
      />
    );
  });

  // The suggested "Save as PDF" file name comes from the document title.
  const previousTitle = document.title;
  const exportTitle = `${fileName}-${format(exportedAt, 'yyyy-MM-dd-HHmmss')}`;
  document.title = exportTitle;
  document.documentElement.classList.add('fs-printing');

  try {
    if (document.fonts?.ready) await document.fonts.ready;
  } catch {
    /* printing with fallback fonts is still legible */
  }

  return new Promise((resolve) => {
    let finished = false;
    let fallback = null;
    const finish = () => {
      if (finished) return;
      finished = true;
      window.removeEventListener('afterprint', finish);
      clearTimeout(fallback);
      document.documentElement.classList.remove('fs-printing');
      document.title = previousTitle;
      root.unmount();
      host.remove();
      style.remove();
      resolve(true);
    };
    window.addEventListener('afterprint', finish);
    // Browsers whose print() returns before the dialog closes still fire
    // afterprint; the fallback only guarantees cleanup.
    fallback = setTimeout(finish, 120000);
    // The app may have re-rendered its own title while fonts loaded.
    document.title = exportTitle;
    window.print();
  });
}

export default exportChatToPdf;
